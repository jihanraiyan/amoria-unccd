// World registry and loaders. One abstraction for both kinds of world:
// - the procedural Amoria Valley (fictional, generated in code, always available), and
// - real-data-derived worlds exported by scripts/geodata to public/world-data/*.json.
// The game can list every world synchronously (metadata only) and load any of them as a
// WorldInput, so the same gameplay runs on either.
import { generateProceduralWorld } from '../simulation/world/procedural'
import type { WorldInput, WorldMeta } from '../simulation/types'
import { REAL_WORLDS } from './realWorlds.generated'
import { WorldLoadError, parseWorldText, type LoadedWorld, type WorldDetails } from './worldFile'

export const PROCEDURAL_WORLD_ID = 'amoria-valley'
/** The procedural terrain is fixed; the game seed drives weather, not terrain shape. */
export const PROCEDURAL_TERRAIN_SEED = 1
/** Preferred starting world: the real-data catchment when it is bundled, else the valley. */
export const DEFAULT_WORLD_ID = REAL_WORLDS[0]?.meta.id ?? PROCEDURAL_WORLD_ID
export const FALLBACK_WORLD_ID = PROCEDURAL_WORLD_ID

export type WorldSource = { type: 'procedural'; seed: number } | { type: 'file'; file: string }

export interface WorldListing {
  meta: WorldMeta
  source: WorldSource
  /** Loads the full world. Real-data worlds are fetched and validated on demand. */
  load(options?: LoadOptions): Promise<LoadedWorld>
}

export interface LoadOptions {
  /** Injected fetch (tests, workers). Defaults to globalThis.fetch. */
  fetchFn?: typeof fetch
  /** Base URL the site is served from. Defaults to Vite's BASE_URL. */
  baseUrl?: string
  signal?: AbortSignal
}

const PROCEDURAL_DETAILS: WorldDetails = {
  attribution: [],
  disclosures: [
    'Amoria Valley is a made-up landscape generated by the game. It is not based on any real place or measured data.',
    'Soil health, water and yields are model values in game units, not measurements.',
  ],
  places: [],
}

let proceduralCache: WorldInput | null = null
function proceduralWorld(): WorldInput {
  if (!proceduralCache) proceduralCache = generateProceduralWorld(PROCEDURAL_TERRAIN_SEED)
  return proceduralCache
}

/** A fresh copy so callers can never mutate the cached arrays. */
function copyWorld(w: WorldInput): WorldInput {
  return {
    ...w,
    elevationM: w.elevationM.slice(),
    cover: w.cover.slice(),
    structure: w.structure?.slice(),
    structureLevel: w.structureLevel?.slice(),
    protected: w.protected?.slice(),
    channel: w.channel?.slice(),
    irrigated: w.irrigated?.slice(),
    intensity: w.intensity?.slice(),
  }
}

function defaultBaseUrl(): string {
  const base = import.meta.env?.BASE_URL
  return typeof base === 'string' && base.length > 0 ? base : '/'
}

/** URL of a world file under public/world-data/, respecting the deploy base path. */
export function worldFileUrl(file: string, baseUrl = defaultBaseUrl()): string {
  const base = baseUrl.endsWith('/') ? baseUrl : `${baseUrl}/`
  return `${base}world-data/${encodeURIComponent(file)}`
}

async function fetchWorldFile(id: string, file: string, options: LoadOptions = {}): Promise<LoadedWorld> {
  const fetchFn = options.fetchFn ?? globalThis.fetch
  if (typeof fetchFn !== 'function') {
    throw new WorldLoadError('network', 'This browser cannot download map files.', ['fetch is not available'])
  }
  const url = worldFileUrl(file, options.baseUrl)
  let res: Response
  try {
    res = await fetchFn(url, { signal: options.signal })
  } catch (err) {
    if (err instanceof DOMException && err.name === 'AbortError') throw err
    throw new WorldLoadError('network', 'The map could not be downloaded. Check your connection and try again.', [
      `${url}: ${err instanceof Error ? err.message : String(err)}`,
    ])
  }
  if (!res.ok) {
    throw new WorldLoadError('network', 'The map could not be downloaded. Check your connection and try again.', [
      `${url}: HTTP ${res.status}`,
    ])
  }
  return parseWorldText(await res.text(), id)
}

const proceduralListing: WorldListing = {
  meta: proceduralWorld().meta,
  source: { type: 'procedural', seed: PROCEDURAL_TERRAIN_SEED },
  load: async () => ({ ...copyWorld(proceduralWorld()), details: PROCEDURAL_DETAILS }),
}

const realListings: WorldListing[] = REAL_WORLDS.map((r) => ({
  meta: r.meta,
  source: { type: 'file', file: r.file },
  load: (options?: LoadOptions) => fetchWorldFile(r.meta.id, r.file, options),
}))

/** Every world this build can play, procedural first. Synchronous: metadata only. */
export function listWorlds(): WorldListing[] {
  return [proceduralListing, ...realListings]
}

export function getWorldListing(id: string): WorldListing | undefined {
  return listWorlds().find((w) => w.meta.id === id)
}

/** Load a world by id, validated against the WorldInput contract. */
export async function loadWorld(id: string, options?: LoadOptions): Promise<LoadedWorld> {
  const listing = getWorldListing(id)
  if (!listing) {
    throw new WorldLoadError('unknown-world', 'That map is not available in this version of Amoria.', [`no world with id "${id}"`])
  }
  return listing.load(options)
}

export interface LoadResult {
  world: LoadedWorld
  /** True when the requested world failed and the procedural valley was loaded instead. */
  fellBack: boolean
  error?: WorldLoadError
}

/** Load a world, falling back to the procedural valley so the game always starts. */
export async function loadWorldWithFallback(id: string, options?: LoadOptions): Promise<LoadResult> {
  try {
    return { world: await loadWorld(id, options), fellBack: false }
  } catch (err) {
    if (id === FALLBACK_WORLD_ID) throw err
    if (err instanceof DOMException && err.name === 'AbortError') throw err
    const error =
      err instanceof WorldLoadError ? err : new WorldLoadError('invalid', 'The map could not be loaded.', [String(err)])
    return { world: await loadWorld(FALLBACK_WORLD_ID), fellBack: true, error }
  }
}
